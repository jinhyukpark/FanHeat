-- Expand the React/Supabase back office so artists, posts, and nested comments
-- can be managed without the removed Spring service.

alter table public.artists
  add column if not exists real_name text,
  add column if not exists role_description text,
  add column if not exists debut_text text,
  add column if not exists agency text,
  add column if not exists fandom_name text,
  add column if not exists hero_image_url text,
  add column if not exists bio_paragraphs text[] not null default '{}',
  add column if not exists history_items jsonb not null default '[]'::jsonb,
  add column if not exists award_items jsonb not null default '[]'::jsonb,
  add column if not exists follower_count bigint not null default 0 check (follower_count >= 0),
  add column if not exists visitor_today bigint not null default 0 check (visitor_today >= 0),
  add column if not exists visitor_total bigint not null default 0 check (visitor_total >= 0),
  add column if not exists facebook_url text,
  add column if not exists x_url text,
  add column if not exists instagram_url text,
  add column if not exists updated_at timestamptz not null default now();

create table if not exists public.artist_albums (
  id bigint generated by default as identity primary key,
  artist_id bigint not null references public.artists(id) on delete cascade,
  title text not null check (char_length(title) between 1 and 200),
  lead_track text not null default '',
  release_date date,
  album_type text not null default '앨범',
  track_count integer not null default 1 check (track_count between 0 and 200),
  cover_url text,
  youtube_url text,
  active boolean not null default true,
  display_order integer not null default 0,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.artist_gallery_items (
  id bigint generated by default as identity primary key,
  artist_id bigint not null references public.artists(id) on delete cascade,
  title text not null check (char_length(title) between 1 and 200),
  image_url text not null,
  captured_on date,
  active boolean not null default true,
  display_order integer not null default 0,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.artist_fans (
  id bigint generated by default as identity primary key,
  artist_id bigint not null references public.artists(id) on delete cascade,
  profile_id uuid references public.profiles(id) on delete set null,
  display_name text not null,
  handle text not null,
  avatar_url text,
  heat_percent integer not null default 0 check (heat_percent between 0 and 100),
  featured_rank integer check (featured_rank between 1 and 999),
  active boolean not null default true,
  display_order integer not null default 0,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

-- Only structural deletion metadata is public. The deleted comment body remains
-- protected by the comments RLS policy and is never copied into this table.
create table if not exists public.comment_tombstones (
  comment_id uuid primary key references public.comments(id) on delete cascade,
  post_id uuid not null references public.posts(id) on delete cascade,
  parent_id uuid,
  deleted_at timestamptz not null default now()
);

create index if not exists artist_albums_artist_order_idx
  on public.artist_albums(artist_id, active desc, display_order, release_date desc);
create index if not exists artist_gallery_artist_order_idx
  on public.artist_gallery_items(artist_id, active desc, display_order, captured_on desc);
create index if not exists artist_fans_artist_order_idx
  on public.artist_fans(artist_id, active desc, display_order, featured_rank);
create index if not exists comment_tombstones_post_idx
  on public.comment_tombstones(post_id, deleted_at);
create index if not exists comment_tombstones_parent_idx
  on public.comment_tombstones(parent_id) where parent_id is not null;

