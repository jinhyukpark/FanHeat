-- Keep post media editable by the post owner and by a super administrator.
drop policy if exists post_images_owner_insert on public.post_images;
drop policy if exists post_images_owner_update on public.post_images;
drop policy if exists post_images_owner_delete on public.post_images;
drop policy if exists post_images_owner_or_admin_insert on public.post_images;
drop policy if exists post_images_owner_or_admin_update on public.post_images;
drop policy if exists post_images_owner_or_admin_delete on public.post_images;
create policy post_images_owner_or_admin_insert on public.post_images
  for insert to authenticated with check (exists (
    select 1 from public.posts p
    where p.id = post_id and (p.author_id = (select auth.uid()) or (select public.is_admin()))
  ));
create policy post_images_owner_or_admin_update on public.post_images
  for update to authenticated using (exists (
    select 1 from public.posts p
    where p.id = post_id and (p.author_id = (select auth.uid()) or (select public.is_admin()))
  )) with check (exists (
    select 1 from public.posts p
    where p.id = post_id and (p.author_id = (select auth.uid()) or (select public.is_admin()))
  ));
create policy post_images_owner_or_admin_delete on public.post_images
  for delete to authenticated using (exists (
    select 1 from public.posts p
    where p.id = post_id and (p.author_id = (select auth.uid()) or (select public.is_admin()))
  ));

